// جميع الأسئلة في مصفوفة واحدة للاختيار العشوائي
export const allQuestions: QuizQuestion[] = quizCategories.flatMap(cat => cat.questions);

// الحصول على أسئلة عشوائية من فئة معينة أو من جميع الفئات
export function getRandomQuestions(count: number = 5, categoryId?: string): QuizQuestion[] {
  const pool = categoryId 
    ? quizCategories.find(c => c.id === categoryId)?.questions || allQuestions
    : allQuestions;
  
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}

// الحصول على معلومات الفئة لسؤال معين
export function getCategoryForQuestion(questionId: number): QuizCategory | undefined {
  return quizCategories.find(cat => cat.questions.some(q => q.id === questionId));
}

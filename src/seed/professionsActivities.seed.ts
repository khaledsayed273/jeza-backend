export async function seedProfessionsActivities(db: MySql2Database<any>) {
  console.log("  → Seeding normalized professionCategories / activities2026...");

  // profession categories
  await db.delete(professionCategoryPhases);
  await db.delete(professionCategoryJobs);
  await db.delete(professionCategoriesTable);

  for (const cat of professionCategories) {
    await db.insert(professionCategoriesTable).values({
      id: cat.id,
      label: cat.label,
      required: cat.required,
      note: cat.note,
      examples: cat.examples,
      minWage: cat.minWage,
    });
    if (cat.jobs) {
      await db.insert(professionCategoryJobs).values(
        cat.jobs.map((j, i) => ({ categoryId: cat.id, name: j.name, minWage: j.minWage, sortOrder: i })),
      );
    }
    if (cat.phases) {
      await db.insert(professionCategoryPhases).values(
        cat.phases.map((p, i) => ({ categoryId: cat.id, date: p.date, rate: p.rate, label: p.label, sortOrder: i })),
      );
    }
  }

  // activities 2026
  await db.delete(activities2026Table);
  await db.insert(activities2026Table).values(
    ACTIVITIES_2026.map((a, i) => ({
      name: a.name,
      mLow: String(a.m.low),
      mMid: String(a.m.mid),
      mHigh: String(a.m.high),
      mPlat: String(a.m.plat),
      thLow: String(a.th.low),
      thMid: String(a.th.mid),
      thHigh: String(a.th.high),
      thPlat: String(a.th.plat),
      sortOrder: i,
    })),
  );

  console.log("    ✓ professionCategories (" + professionCategories.length + " categories)");
  console.log("    ✓ activities2026 (" + ACTIVITIES_2026.length + " activities)");
}
